// Build script
const scraped = JSON.parse(fs.readFileSync('scraped_playlist.json', 'utf8'));

const cameras: any[] = [];
const attractionCameraMap: Record<string, string[]> = {};

// Initialize attraction camera list
Object.keys(ATTRACTION_REGISTRY).forEach((id) => {
  attractionCameraMap[id] = [];
});

let pendingCount = 0;
let geocodedCount = 0;

scraped.forEach((item: any, idx: number) => {
  const videoId = item.videoId;
  const title = item.title || `影片 [${videoId}] (暫無標題或離線)`;
  const isEmbeddable = item.embeddable !== false && item.statusCode !== 403;
  const cameraId = `cam-${videoId}`;

  // Match against attraction registry
  let matchedAttrId: string | null = null;
  for (const [attrId, attrInfo] of Object.entries(ATTRACTION_REGISTRY)) {
    const isMatch = attrInfo.matchPatterns.some((pattern) => {
      if (typeof pattern === 'string') {
        return title.includes(pattern);
      }
      return pattern.test(title);
    });

    if (isMatch) {
      matchedAttrId = attrId;
      break;
    }
  }

  if (matchedAttrId) {
    attractionCameraMap[matchedAttrId].push(cameraId);
    geocodedCount++;
  } else {
    pendingCount++;
  }

  // Stream status: If it came from the YouTube playlist with valid oEmbed, marked live/standby
  const isAvailable = Boolean(item.title);
  const streamStatus = isAvailable ? 'live' : 'offline';

  cameras.push({
    cameraId,
    videoId,
    playlistItemId: `item-pl-${idx + 1}`,
    title,
    description: `官方來源: ${item.author || 'YouTube 直播串流'}。此鏡頭來自 YouTube 台灣觀光即時影像指定播放清單。`,
    thumbnailUrl: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
    streamStatus,
    embeddable: isEmbeddable,
    videoUrl: `https://www.youtube.com/watch?v=${videoId}`,
    lastCheckedAt: new Date().toISOString(),
    attractionId: matchedAttrId,
  });
});

// Construct attractions list (only those with matched cameras)
const attractions: any[] = [];

Object.entries(ATTRACTION_REGISTRY).forEach(([id, meta]) => {
  const cIds = attractionCameraMap[id] || [];
  if (cIds.length > 0) {
    attractions.push({
      attractionId: id,
      name: meta.name,
      city: meta.city,
      region: meta.region,
      latitude: meta.latitude,
      longitude: meta.longitude,
      coordinateSource: meta.coordinateSource,
      coordinateAccuracy: meta.coordinateAccuracy,
      landmarkType: meta.landmarkType,
      cameraIds: cIds,
      checkinEnabled: meta.checkinEnabled,
      checkinRadiusMeters: meta.checkinRadiusMeters,
    });
  }
});

// Ensure directory exists
fs.mkdirSync('src/data', { recursive: true });

fs.writeFileSync('src/data/cameras.json', JSON.stringify(cameras, null, 2));
fs.writeFileSync('src/data/attractions.json', JSON.stringify(attractions, null, 2));

console.log(`Generated cameras.json: ${cameras.length} items`);
console.log(`Generated attractions.json: ${attractions.length} attractions`);
console.log(`Geocoded cameras: ${geocodedCount}, Pending geolocation cameras: ${pendingCount}`);
